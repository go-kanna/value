package gen_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/go-kanna/internal/packages"
	"github.com/go-kanna/internal/pkgtest"

	"github.com/go-kanna/value/internal/gen"
)

// targets loads files as one package and finds its targets, as gen.Targets
// spells them.
func targets(t *testing.T, files map[string]string) ([]string, []string) {
	t.Helper()

	pkg := pkgtest.Load(t, files)
	return gen.Targets(pkg.Fset, []*packages.Package{pkg})
}

func TestTargets(t *testing.T) {
	t.Parallel()

	names, diags := targets(t, map[string]string{
		"model.go": `package test

import "time"

//kanna:value
type CompletedAt struct{ t time.Time }

func (c CompletedAt) Before(o CompletedAt) bool { return c.t.Before(o.t) }

func (CompletedAt) validate(time.Time) error { return nil }

//kanna:value
type Email struct{ s string }

func (Email) validate(string) error { return nil }

// Equal is free to declare, as a string has no Equal method to generate one
// for.
func (e Email) Equal(o Email) bool { return e == o }

type cents int64

//kanna:value
type price struct{ c cents }

func (price) validate(cents) error { return nil }

//kanna:value
type Code struct{ b byte }

func (Code) validate(byte) error { return nil }

// level has a String method, but not one fmt calls.
type level int

func (level) String() int { return 0 }

//kanna:value
type Level struct{ l level }

func (Level) validate(level) error { return nil }

type tags []string

//kanna:value
type Tags struct{ t tags }

func (Tags) validate(tags) error { return nil }

type labels map[string]string

//kanna:value
type Labels struct{ l labels }

func (Labels) validate(labels) error { return nil }

type address struct{ lines []string }

//kanna:value
type Address struct{ a address }

func (Address) validate(address) error { return nil }

// IsZero is free to declare, as none is generated for an address.
func (a Address) IsZero() bool { return len(a.a.lines) == 0 }

// éclair starts with a letter of two bytes, which its constructors
// capitalize whole.
//
//kanna:value
type éclair struct{ n int }

func (éclair) validate(int) error { return nil }

//kanna:value
type Regenerated struct{ n int }

func (Regenerated) validate(int) error { return nil }

type Plain struct{ t time.Time }
`,
		// What an earlier run left behind, which the next run replaces.
		"value_gen.go": `// Code generated by kanna-value. DO NOT EDIT.

package test

func NewRegenerated(n int) (Regenerated, error) { return Regenerated{n: n}, nil }

func (x Regenerated) Int() int { return x.n }

func (x Regenerated) String() string { return "" }
`,
	})

	want := []string{
		"CompletedAt{t time.Time} Time() zero=IsZero Equal String NewCompletedAt/MustCompletedAt",
		"Email{s string} String() zero=compare NewEmail/MustEmail",
		"price{c cents} Cents() zero=compare newPrice/mustPrice",
		"Code{b byte} Byte() zero=compare NewCode/MustCode",
		"Level{l level} Level() zero=compare NewLevel/MustLevel",
		"Tags{t tags} Tags() zero=nil clone=slices NewTags/MustTags",
		"Labels{l labels} Labels() zero=nil clone=maps NewLabels/MustLabels",
		"Address{a address} Address() zero=none NewAddress/MustAddress",
		"éclair{n int} Int() zero=compare newÉclair/mustÉclair",
		"Regenerated{n int} Int() zero=compare NewRegenerated/MustRegenerated",
	}
	if !slices.Equal(names, want) {
		t.Errorf("targets = %q, want %q", names, want)
	}
	if len(diags) > 0 {
		t.Errorf("diagnostics = %q, want none", diags)
	}
}

func TestTargets_Diagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "misspelled directive",
			src: `package test

//kanna:valeu
type Email struct{ s string }
`,
			want: `did you mean "//kanna:value"?`,
		},
		{
			name: "arguments",
			src: `package test

//kanna:value strict
type Email struct{ s string }

func (Email) validate(string) error { return nil }
`,
			want: `test.go:3:1: error: //kanna:value takes no arguments, got "strict"`,
		},
		{
			name: "generic",
			src: `package test

//kanna:value
type Box[T comparable] struct{ v T }
`,
			want: "test.go:4:6: error: generic struct Box is not supported",
		},
		{
			name: "no field",
			src: `package test

//kanna:value
type Empty struct{}
`,
			want: "test.go:4:6: error: Empty must have exactly one field, the value it holds, but has 0",
		},
		{
			name: "two fields",
			src: `package test

//kanna:value
type Pair struct{ a, b int }
`,
			want: "Pair must have exactly one field, the value it holds, but has 2",
		},
		{
			name: "exported field",
			src: `package test

//kanna:value
type ID struct{ Value string }
`,
			want: "test.go:4:17: error: ID.Value must be unexported, so that a value is set only through the generated code\n" +
				"  rename it to value",
		},
		{
			name: "exported field starting with a letter of two bytes",
			src: `package test

//kanna:value
type Pastry struct{ Éclair string }
`,
			want: "  rename it to éclair",
		},
		{
			name: "embedded field",
			src: `package test

import "time"

//kanna:value
type At struct{ time.Time }
`,
			want: "test.go:6:22: error: At embeds time.Time; give the field a name",
		},
		{
			name: "blank field",
			src: `package test

//kanna:value
type Blank struct{ _ int }
`,
			want: "the field of Blank needs a name for the generated code to refer to it by",
		},
		{
			name: "interface",
			src: `package test

//kanna:value
type Failure struct{ err error }
`,
			want: "Failure holds an interface, error, whose dynamic value no rule can be written for",
		},
		{
			name: "unnamed type",
			src: `package test

//kanna:value
type Tags struct{ t []string }
`,
			want: "Tags holds a []string, which has no name to call the method returning it after\n" +
				"  declare a named type for it, and hold that",
		},
		{
			name: "no validate method",
			src: `package test

//kanna:value
type Email struct{ s string }
`,
			want: "test.go:4:6: error: Email has no validate method to check its values with\n" +
				"  add func (Email) validate(string) error, returning nil to accept the value",
		},
		{
			name: "validate taking another type",
			src: `package test

//kanna:value
type Email struct{ s string }

func (Email) validate(int) error { return nil }
`,
			want: "test.go:6:14: error: Email.validate must be func (Email) validate(string) error " +
				"for the generated code to check values with",
		},
		{
			name: "validate on a pointer",
			src: `package test

//kanna:value
type Email struct{ s string }

func (*Email) validate(string) error { return nil }
`,
			want: "Email.validate must be func (Email) validate(string) error",
		},
		{
			name: "validate returning a bool",
			src: `package test

//kanna:value
type Email struct{ s string }

func (Email) validate(string) bool { return true }
`,
			want: "Email.validate must be func (Email) validate(string) error",
		},
		{
			name: "hand-written generated method",
			src: `package test

import "time"

//kanna:value
type CompletedAt struct{ t time.Time }

func (CompletedAt) validate(time.Time) error { return nil }

func (c CompletedAt) String() string { return "" }
`,
			want: "test.go:10:22: error: CompletedAt already has a method named String\n" +
				"  remove it, or the //kanna:value on CompletedAt",
		},
		{
			name: "hand-written accessor",
			src: `package test

//kanna:value
type Email struct{ s string }

func (Email) validate(string) error { return nil }

func (e Email) String() string { return "" }
`,
			want: "Email already has a method named String",
		},
		{
			name: "hand-written Equal where one is generated",
			src: `package test

import "time"

//kanna:value
type CompletedAt struct{ t time.Time }

func (CompletedAt) validate(time.Time) error { return nil }

func (c CompletedAt) Equal(o CompletedAt) bool { return false }
`,
			want: "CompletedAt already has a method named Equal",
		},
		{
			name: "accessor named as a generated method",
			src: `package test

type Value int

//kanna:value
type Amount struct{ v Value }

func (Amount) validate(Value) error { return nil }
`,
			want: "the accessor of Amount would be named Value, after its type Value, which collides with a generated method",
		},
		{
			name: "hand-written constructor",
			src: `package test

//kanna:value
type Email struct{ s string }

func (Email) validate(string) error { return nil }

func NewEmail(s string) Email { return Email{s: s} }
`,
			want: "test.go:8:6: error: NewEmail is already declared, so it cannot be generated as a constructor of Email\n" +
				"  remove it, or the //kanna:value on Email",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			names, diags := targets(t, map[string]string{"test.go": tt.src})
			if len(names) > 0 {
				t.Errorf("targets = %q, want none", names)
			}
			if !slices.ContainsFunc(diags, func(d string) bool { return strings.Contains(d, tt.want) }) {
				t.Errorf("diagnostics = %q, want one containing %q", diags, tt.want)
			}
		})
	}
}
