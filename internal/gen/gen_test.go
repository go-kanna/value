func TestCommand_WarnsWhenNothingIsMarked(t *testing.T) {
	t.Parallel()

	const plain = "package app\n\ntype Email struct{ s string }\n"
	tests := []struct {
		name  string
		files map[string]string
		args  []string
		want  string
	}{
		{
			name:  "the package in the directory",
			files: map[string]string{"app.go": plain},
			want:  "warning: nothing is marked //kanna:value or //kanna:enum in example.com/app\n",
		},
		{
			name: "every package",
			files: map[string]string{
				"app.go":         plain,
				"other/other.go": strings.Replace(plain, "package app", "package other", 1),
			},
			args: []string{"./..."},
			want: "warning: nothing is marked //kanna:value or //kanna:enum in example.com/app, example.com/app/other\n",
		},
		{
			name:  "patterns matching no package",
			files: map[string]string{},
			args:  []string{"./..."},
			want:  "warning: nothing is marked //kanna:value or //kanna:enum in ./...\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, tt.files)
			if code, _, stderr := run(t, dir, tt.args...); code != cli.ExitOK || stderr != tt.want {
				t.Errorf("run = %d, stderr %q; want success with %q", code, stderr, tt.want)
			}
		})
	}
}

