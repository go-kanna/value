func TestCommand_Check(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	path := filepath.Join(dir, "value_gen.go")

	code, _, stderr := run(t, dir, "-check")
	if want := "./value_gen.go: error: not generated yet; run go generate\n"; code != cli.ExitFailure ||
		stderr != want {
		t.Errorf("-check before generating = %d, stderr %q; want %q", code, stderr, want)
	}

	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}
	before := readFile(t, path)
	writeFile(t, filepath.Join(dir, "app.go"), strings.Replace(appSrc, "struct{ s string }", "struct{ addr string }", 1))

	code, _, stderr = run(t, dir, "-check")
	if want := "./value_gen.go: error: out of date; run go generate\n"; code != cli.ExitFailure || stderr != want {
		t.Errorf("-check after a change = %d, stderr %q; want %q", code, stderr, want)
	}
	if readFile(t, path) != before {
		t.Error("-check rewrote value_gen.go")
	}
}

func TestCommand_RemovesLeftover(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	path := filepath.Join(dir, "value_gen.go")
	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}
	writeFile(t, filepath.Join(dir, "app.go"), "package app\n\ntype Email struct{ s string }\n")
	const nothing = "warning: nothing is marked //kanna:value or //kanna:enum in example.com/app\n"

	code, _, stderr := run(t, dir, "-check")
	want := nothing + "./value_gen.go: error: left over from an earlier run; run go generate\n"
	if code != cli.ExitFailure || stderr != want {
		t.Errorf("-check = %d, stderr %q; want %q", code, stderr, want)
	}

	code, stdout, stderr := run(t, dir, "-v")
	if code != cli.ExitOK || stdout != "removed ./value_gen.go\n" || stderr != nothing {
		t.Errorf("run = %d, stdout %q, stderr %q; want the removal and a warning", code, stdout, stderr)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Errorf("value_gen.go still exists: %v", err)
	}

	// Once the file is gone, a run says the same and succeeds the same.
	if code, _, stderr := run(t, dir); code != cli.ExitOK || stderr != nothing {
		t.Errorf("run again = %d, stderr %q; want success with the warning", code, stderr)
	}
}

// Renaming the field leaves the earlier output referring to one that is gone,
// which must not stop the run that would fix it.
func TestCommand_RegeneratesOverStaleOutput(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}
	writeFile(t, filepath.Join(dir, "app.go"), strings.Replace(appSrc, "struct{ s string }", "struct{ addr string }", 1))

	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run over stale output = %d, stderr %q", code, stderr)
	}
	if got := readFile(t, filepath.Join(dir, "value_gen.go")); !strings.Contains(got, "return x.addr") {
		t.Errorf("value_gen.go was not regenerated:\n%s", got)
	}
}

// Setting a stale file aside only helps with the errors it caused. Anything
// else still fails the run, which then says why the file was set aside.
func TestCommand_SaysWhatWasSetAside(t *testing.T) {
	t.Parallel()

	dir := writeModule(t, map[string]string{"app.go": appSrc})
	if code, _, stderr := run(t, dir); code != cli.ExitOK {
		t.Fatalf("run = %d, stderr %q", code, stderr)
	}
	// Renaming the struct breaks the receivers of the generated methods, so the
	// whole file is set aside, and the unrelated error remains.
	renamed := strings.ReplaceAll(appSrc, "Email", "Address") + "\nvar broken int = \"x\"\n"
	writeFile(t, filepath.Join(dir, "app.go"), renamed)

	code, _, stderr := run(t, dir)
	if code != cli.ExitFailure {
		t.Fatalf("run = %d, want %d; stderr %q", code, cli.ExitFailure, stderr)
	}
	for _, want := range []string{
		`./app.go:19:18: error: cannot use "x"`,
		"./value_gen.go: warning: set aside because it no longer compiles; " +
			"it is regenerated once the errors above are fixed",
	} {
		if !strings.Contains(stderr, want) {
			t.Errorf("stderr = %q, want it to contain %q", stderr, want)
		}
	}
}

func TestCommand_Failures(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{
			name: "target error",
			files: map[string]string{
				"app.go": strings.Replace(appSrc, "func (Email) validate(s string) error { return rule.Email(s) }",
					"var _ = rule.Email", 1),
			},
			want: "./app.go:10:6: error: Email has no validate method to check its values with\n" +
				"  add func (Email) validate(string) error, returning nil to accept the value\n",
		},
		{
			name:  "directive with arguments",
			files: map[string]string{"app.go": strings.Replace(appSrc, "//kanna:value", "//kanna:value strict", 1)},
			want:  "./app.go:9:1: error: //kanna:value takes no arguments, got \"strict\"\n",
		},
		{
			name:  "type error elsewhere",
			files: map[string]string{"app.go": appSrc + "\nvar broken int = \"x\"\n"},
			want:  `./app.go:19:18: error: cannot use "x"`,
		},
		{
			// Only what the run generates is let past.
			name:  "a constructor of a struct not marked",
			files: map[string]string{"app.go": appSrc + "\nvar _ = NewPhone(\"0120\")\n"},
			want:  "./app.go:19:9: error: undefined: NewPhone\n",
		},
		{
			name:  "a method not generated",
			files: map[string]string{"app.go": appSrc + "\nfunc f(e Email) string { return e.Domain() }\n"},
			want:  "./app.go:19:35: error: e.Domain undefined (type Email has no field or method Domain)\n",
		},
		{
			name:  "hand-written output",
			files: map[string]string{"app.go": appSrc, "value_gen.go": "package app\n"},
			want:  "./value_gen.go: error: has no generated-code header, so it looks hand-written",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, tt.files)
			code, _, stderr := run(t, dir)
			if code != cli.ExitFailure || !strings.Contains(stderr, tt.want) {
				t.Errorf("run = %d, stderr %q; want %d and %q", code, stderr, cli.ExitFailure, tt.want)
			}
		})
	}
}

