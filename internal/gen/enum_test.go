package gen_test

import (
	"slices"
	"strings"
	"testing"

	"github.com/go-kanna/internal/packages"
	"github.com/go-kanna/internal/pkgtest"

	"github.com/go-kanna/value/internal/gen"
)

// enums loads files as one package and finds its enums, as gen.Enums spells
// them.
func enums(t *testing.T, files map[string]string) ([]string, []string) {
	t.Helper()

	pkg := pkgtest.Load(t, files)
	return gen.Enums(pkg.Fset, []*packages.Package{pkg})
}

func TestEnums(t *testing.T) {
	t.Parallel()

	names, diags := enums(t, map[string]string{
		"model.go": `package test

//kanna:enum
type Status string

const (
	StatusPlaced  Status = "placed"
	StatusPaid    Status = "paid"
	statusHidden  Status = "hidden"
)

//kanna:enum
type kind string

const kindA kind = "a"

//kanna:enum
type Regenerated string

const RegeneratedA Regenerated = "a"

type Plain string

const PlainA Plain = "a"
`,
		"more.go": "package test\n\nconst StatusShipped Status = \"shipped\"\n",
		// What an earlier run left behind, which the next run replaces.
		"value_gen.go": `// Code generated by kanna-value. DO NOT EDIT.

package test

func NewRegenerated(v string) (Regenerated, error) { return Regenerated(v), nil }

func (x *Regenerated) Scan(any) error { return nil }
`,
	})

	want := []string{
		"Status placed,paid,hidden,shipped NewStatus/StatusValues",
		"kind a newKind/kindValues",
		"Regenerated a NewRegenerated/RegeneratedValues",
	}
	if !slices.Equal(names, want) {
		t.Errorf("enums = %q, want %q", names, want)
	}
	if len(diags) > 0 {
		t.Errorf("diagnostics = %q, want none", diags)
	}
}

func TestEnums_Diagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "misspelled directive",
			src: `package test

//kanna:enmu
type Status string

const StatusA Status = "a"
`,
			want: `did you mean "//kanna:enum"?`,
		},
		{
			name: "arguments",
			src: `package test

//kanna:enum strict
type Status string

const StatusA Status = "a"
`,
			want: `test.go:3:1: error: //kanna:enum takes no arguments, got "strict"`,
		},
		{
			name: "generic",
			src: `package test

//kanna:enum
type Status[T any] string
`,
			want: "test.go:4:6: error: generic type Status is not supported",
		},
		{
			name: "not a string",
			src: `package test

//kanna:enum
type Level int

const LevelA Level = 1
`,
			want: "test.go:4:6: error: Level must be a string type to be an enum, but its underlying type is int\n" +
				"  declare it as type Level string",
		},
		{
			name: "no constants",
			src: `package test

//kanna:enum
type Status string

const StatusA = "a"
`,
			want: "test.go:4:6: error: Status has no constants to be one of\n" +
				`  declare them beside it, such as const StatusA Status = "a"`,
		},
		{
			name: "the zero value",
			src: `package test

//kanna:enum
type Status string

const (
	StatusNone Status = ""
	StatusA    Status = "a"
)
`,
			want: `test.go:7:2: error: StatusNone holds "", the zero value of Status, which stands for none` + "\n" +
				"  remove it, and use a *Status where a value may be absent",
		},
		{
			name: "a value held twice",
			src: `package test

//kanna:enum
type Status string

const (
	StatusCanceled  Status = "canceled"
	StatusCancelled Status = "canceled"
)
`,
			want: `test.go:8:2: error: StatusCancelled holds "canceled", as StatusCanceled does` + "\n" +
				"  give each constant a value of its own",
		},
		{
			name: "hand-written generated method",
			src: `package test

//kanna:enum
type Status string

const StatusA Status = "a"

func (s *Status) UnmarshalText([]byte) error { return nil }
`,
			want: "test.go:8:18: error: Status already has a method named UnmarshalText\n" +
				"  remove it, or the //kanna:enum on Status",
		},
		{
			name: "hand-written function",
			src: `package test

//kanna:enum
type Status string

const StatusA Status = "a"

func StatusValues() []Status { return nil }
`,
			want: "test.go:8:6: error: StatusValues is already declared, so it cannot be generated for Status\n" +
				"  remove it, or the //kanna:enum on Status",
		},
		{
			name: "//kanna:enum on a struct",
			src: `package test

//kanna:enum
type Email struct{ s string }
`,
			want: "test.go:4:6: error: Email is a struct, which //kanna:enum does not mark\n" +
				"  mark it //kanna:value to generate a value type",
		},
		{
			name: "//kanna:value on a string type",
			src: `package test

//kanna:value
type Status string

const StatusA Status = "a"
`,
			want: "test.go:4:6: error: Status is not a struct, which //kanna:value marks\n" +
				"  mark it //kanna:enum to accept only the constants declared beside it",
		},
		{
			name: "//kanna:value on another type",
			src: `package test

//kanna:value
type Price int
`,
			want: "test.go:4:6: error: Price is not a struct, which //kanna:value marks\n" +
				"  hold the value in a struct with one unexported field",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			names, diags := enums(t, map[string]string{"test.go": tt.src})
			if len(names) > 0 {
				t.Errorf("enums = %q, want none", names)
			}
			if !slices.ContainsFunc(diags, func(d string) bool { return strings.Contains(d, tt.want) }) {
				t.Errorf("diagnostics = %q, want one containing %q", diags, tt.want)
			}
		})
	}
}
