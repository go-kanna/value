func TestRunStopsOnPackagesThatDoNotLoad(t *testing.T) {
	t.Parallel()

	dir := module(t, model, map[string]string{
		"usecase/usecase.go": `package usecase

import "example.com/m/model"

var _ model.Status = "opne"

var _ = undefined
`,
	})

	got := report(vet.Run(dir, "", []string{"./..."}))
	want := "usecase.go:7:9: error: undefined: undefined"
	if got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}

func TestRunMatchingNoPackages(t *testing.T) {
	t.Parallel()

	dir := module(t, model, map[string]string{"docs/notes.txt": ""})

	got := report(vet.Run(dir, "", []string{"./docs/..."}))
	want := "error: ./docs/... matched no packages"
	if got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}

// module writes the files of each of sets into a module of their own, and
// returns its directory.
func module(t *testing.T, sets ...map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	files := map[string]string{"go.mod": "module example.com/m\n\ngo 1.26\n"}
	for _, set := range sets {
		maps.Copy(files, set)
	}
	for name, src := range files {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// report renders ds as diag does, naming each file by its base name.
func report(ds []diag.Diag) string {
	lines := make([]string, 0, len(ds))
	for _, d := range ds {
		if d.Pos.Filename != "" {
			d.Pos.Filename = filepath.Base(d.Pos.Filename)
		}
		lines = append(lines, d.String())
	}
	return strings.Join(lines, "\n")
}
